#include <iostream>
using namespace std;

int main() {
    // For loop
    cout << "For Loop:" << endl;

    for (int i = 1; i <= 5; i++) {
        cout << i << " ";
    }

    cout << endl;

    // While loop
    cout << "While Loop:" << endl;

    int i = 1;

    while (i <= 5) {
        cout << i << " ";
        i++;
    }

    return 0;
}
